-- UpScale IA: business sector onboarding + isolated knowledge base.
-- Independent of the existing organizations schema. Each auth user owns one profile
-- and exactly 15 copied Q&A records for the sector selected during registration.

create table if not exists public.sales_business_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  business_sector text not null
    check (business_sector in ('digital_services', 'furniture', 'real_estate')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sales_business_knowledge_templates (
  id bigint generated by default as identity primary key,
  business_sector text not null
    check (business_sector in ('digital_services', 'furniture', 'real_estate')),
  question_order smallint not null check (question_order between 1 and 15),
  question text not null,
  answer text not null,
  unique (business_sector, question_order)
);

create table if not exists public.sales_business_knowledge (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  business_sector text not null
    check (business_sector in ('digital_services', 'furniture', 'real_estate')),
  question_order smallint not null check (question_order between 1 and 15),
  question text not null,
  answer text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, question_order)
);

create index if not exists sales_business_knowledge_user_order_idx
  on public.sales_business_knowledge (user_id, question_order);

alter table public.sales_business_profiles enable row level security;
alter table public.sales_business_knowledge_templates enable row level security;
alter table public.sales_business_knowledge enable row level security;

drop policy if exists "sales_business_profile_read_own" on public.sales_business_profiles;
create policy "sales_business_profile_read_own"
  on public.sales_business_profiles for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "sales_business_templates_read_authenticated" on public.sales_business_knowledge_templates;
create policy "sales_business_templates_read_authenticated"
  on public.sales_business_knowledge_templates for select to authenticated
  using (true);

drop policy if exists "sales_business_knowledge_read_own" on public.sales_business_knowledge;
create policy "sales_business_knowledge_read_own"
  on public.sales_business_knowledge for select to authenticated
  using (user_id = (select auth.uid()));

